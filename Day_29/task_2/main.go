// ============================================================
// ЗАДАНИЕ 2: ПАРСИНГ ЛОГОВ
// ============================================================
// Цель: научиться читать файл и разбирать строки лога на части.
//
// Что делаем:
// 1. Создаём структуру LogEntry для хранения одной записи
// 2. Пишем функцию parseLogLine() для разбора строки
// 3. Читаем файл построчно и парсим каждую строку
// 4. Выводим количество записей и первую/последнюю запись
// ============================================================

package main

import (
	"bufio"   // Для построчного чтения файла
	"flag"    // Для флагов командной строки
	"fmt"     // Для вывода
	"os"      // Для работы с файлами
	"strings" // Для работы со строками (разбивка, обрезка)
	"time"    // Для парсинга даты и времени
)

// ============================================================
// СТРУКТУРА LogEntry
// ============================================================
// LogEntry - структура для хранения одной записи лога.
// Каждая запись содержит:
//   - Timestamp - дата и время события
//   - Level     - уровень логирования (INFO, WARNING, ERROR, DEBUG)
//   - Message   - текст сообщения
//
// ============================================================
type LogEntry struct {
	Timestamp time.Time // Время события
	Level     string    // Уровень: INFO, WARNING, ERROR, DEBUG
	Message   string    // Текст сообщения
}

// ============================================================
// ФУНКЦИЯ parseLogLine()
// ============================================================
// parseLogLine - принимает строку лога и превращает её в структуру LogEntry.
//
// Пример входящей строки:
//
//	"2024-01-15 10:30:45 ERROR Failed to connect to database"
//
// Алгоритм:
//  1. Разбиваем строку на 3 части:
//     - часть 0: дата ("2024-01-15")
//     - часть 1: время ("10:30:45")
//     - часть 2: уровень + сообщение ("ERROR Failed to connect to database")
//  2. Соединяем дату и время в одну строку: "2024-01-15 10:30:45"
//  3. Парсим дату/время в объект time.Time
//  4. Разбиваем уровень и сообщение (уровень - первое слово, остальное - сообщение)
//  5. Возвращаем заполненную структуру LogEntry
//
// Возвращает:
//   - LogEntry - заполненная структура
//   - error    - ошибка, если не удалось распарсить строку
//
// ============================================================
func parseLogLine(line string) (LogEntry, error) {
	// -----------------------------------------------------------------
	// ШАГ 1: Разбиваем строку на 3 части по пробелам
	// -----------------------------------------------------------------
	// strings.SplitN(line, " ", 3) - разбивает строку на максимум 3 части
	// Пример: "2024-01-15 10:30:45 ERROR Failed"
	//   → parts[0] = "2024-01-15"
	//   → parts[1] = "10:30:45"
	//   → parts[2] = "ERROR Failed"
	// -----------------------------------------------------------------
	parts := strings.SplitN(line, " ", 3)

	// Если частей меньше 3, значит строка не соответствует формату
	if len(parts) < 3 {
		return LogEntry{}, fmt.Errorf("invalid log format: %s", line)
	}

	// -----------------------------------------------------------------
	// ШАГ 2: Парсим дату и время
	// -----------------------------------------------------------------
	// Соединяем дату и время: "2024-01-15 10:30:45"
	// time.Parse() - превращает строку в объект time.Time
	// Формат "2006-01-02 15:04:05" - это магическая дата в Go.
	// Она означает: год-месяц-день час:минута:секунда
	// -----------------------------------------------------------------
	timestamp, err := time.Parse("2006-01-02 15:04:05", parts[0]+" "+parts[1])
	if err != nil {
		// Если не удалось распарсить дату - возвращаем ошибку
		return LogEntry{}, err
	}

	// -----------------------------------------------------------------
	// ШАГ 3: Разбиваем уровень и сообщение
	// -----------------------------------------------------------------
	// parts[2] = "ERROR Failed to connect"
	// Разбиваем по первому пробелу:
	//   → level = "ERROR"
	//   → message = "Failed to connect"
	// -----------------------------------------------------------------
	levelAndMessage := strings.SplitN(parts[2], " ", 2)
	level := levelAndMessage[0]
	message := ""
	if len(levelAndMessage) > 1 {
		message = levelAndMessage[1]
	}

	// -----------------------------------------------------------------
	// ШАГ 4: Возвращаем результат
	// -----------------------------------------------------------------
	return LogEntry{
		Timestamp: timestamp,
		Level:     level,
		Message:   message,
	}, nil
}

// ============================================================
// ОСНОВНАЯ ФУНКЦИЯ
// ============================================================
func main() {
	// -----------------------------------------------------------------
	// ШАГ 1: Определяем флаг -file
	// -----------------------------------------------------------------
	filePath := flag.String("file", "logs.txt", "путь к файлу логов")
	flag.Parse()

	// -----------------------------------------------------------------
	// ШАГ 2: Открываем файл
	// -----------------------------------------------------------------
	// os.Open() - открывает файл для чтения
	// Возвращает: указатель на файл и ошибку
	// -----------------------------------------------------------------
	file, err := os.Open(*filePath)
	if err != nil {
		// Если файл не открылся - выводим ошибку и выходим
		fmt.Printf("Ошибка открытия файла: %v\n", err)
		os.Exit(1)
	}
	// defer file.Close() - гарантирует, что файл закроется в конце функции
	// Даже если произойдёт ошибка или panic, файл будет закрыт
	defer file.Close()

	// -----------------------------------------------------------------
	// ШАГ 3: Читаем файл построчно
	// -----------------------------------------------------------------
	// bufio.NewScanner() - создаёт сканер для построчного чтения
	// scanner.Scan() - читает следующую строку (возвращает true, если строка есть)
	// scanner.Text() - возвращает текст текущей строки
	// -----------------------------------------------------------------
	scanner := bufio.NewScanner(file)
	var entries []LogEntry // Слайс для хранения всех записей
	lineNum := 0           // Счётчик строк (для отладки)

	// Цикл читает файл до конца
	for scanner.Scan() {
		lineNum++
		line := scanner.Text()

		// Пропускаем пустые строки
		if line == "" {
			continue
		}

		// Парсим строку в структуру LogEntry
		entry, err := parseLogLine(line)
		if err != nil {
			// Если ошибка парсинга - выводим предупреждение, но продолжаем
			fmt.Printf("Ошибка в строке %d: %v\n", lineNum, err)
			continue
		}
		// Добавляем распаршенную запись в слайс
		entries = append(entries, entry)
	}

	// Проверяем, не было ли ошибок при чтении файла
	if err := scanner.Err(); err != nil {
		fmt.Printf("Ошибка чтения файла: %v\n", err)
		os.Exit(1)
	}

	// -----------------------------------------------------------------
	// ШАГ 4: Выводим результаты
	// -----------------------------------------------------------------
	// len(entries) - количество записей в слайсе
	fmt.Printf("Всего записей: %d\n", len(entries))

	// Если записи есть - выводим первую и последнюю
	if len(entries) > 0 {
		fmt.Println("\nПервая запись:")
		fmt.Printf("  Время: %s\n", entries[0].Timestamp.Format("2006-01-02 15:04:05"))
		fmt.Printf("  Уровень: %s\n", entries[0].Level)
		fmt.Printf("  Сообщение: %s\n", entries[0].Message)

		fmt.Println("\nПоследняя запись:")
		last := entries[len(entries)-1]
		fmt.Printf("  Время: %s\n", last.Timestamp.Format("2006-01-02 15:04:05"))
		fmt.Printf("  Уровень: %s\n", last.Level)
		fmt.Printf("  Сообщение: %s\n", last.Message)
	}
}
