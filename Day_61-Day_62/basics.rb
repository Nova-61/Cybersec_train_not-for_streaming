# 1. Переменные и типы
# В Ruby не нужно заранее объявлять тип переменной: тип определяется значением.
# Переменная может получить значение другого типа позже, поэтому Ruby называют
# динамически типизированным языком.
name = "Alex"
age = 30
price = 99.99
is_active = true
puts "Hello, #{name}! Age: #{age}"

# String - строка, Integer - целое число, Float - дробное число,
# true/false - логические значения (Boolean). Интерполяция #{...} вставляет
# результат выражения внутрь строки в двойных кавычках.

# 2. Массивы и хеши
# Array хранит значения по индексам, начиная с 0. Элементы могут иметь
# разные типы. Получение: arr[0], добавление: arr << 6.
arr = [1, 2, 3, 4, 5]
# Hash хранит пары ключ => значение. Символьная запись name: "Alex" равна
# обычной записи :name => "Alex". Получение значения: hash[:name].
hash = { name: "Alex", age: 30, city: "Moscow" }

# 3. Условные операторы
# if проверяет условие сверху вниз. Выполняется только первая подходящая ветка.
# Условия также можно записать в одну строку: puts "Adult" if age >= 18.
if age >= 18
  puts "Adult"
elsif age > 12
  puts "Teenager"
else
  puts "Child"
end

# 4. Циклы
# Диапазон 1..5 включает обе границы. Диапазон 1...5 не включает последнюю.
# each передаёт каждый элемент в блок между do и end.
(1..5).each do |i|
  puts "Number: #{i}"
end

# each_with_index передаёт в блок и элемент, и его индекс.
# Другие распространённые варианты перебора: while, until, for и times.
arr.each_with_index do |val, idx|
  puts "arr[#{idx}] = #{val}"
end

# 5. Функции (def)
# def создаёт метод. Параметр greeting = "Hello" имеет значение по умолчанию.
# В Ruby return часто не пишут: методом становится результат последнего выражения.
# Явный return нужен, если требуется немедленно выйти из метода.
def greet(name, greeting = "Hello")
  "#{greeting}, #{name}!"
end

puts greet("Alex")               # Hello, Alex!
puts greet("Alex", "Hi")         # Hi, Alex!

# 6. Блоки и лямбды
# Блок - кусок кода, передаваемый методу. Его можно записать через do...end
# или в фигурных скобках { ... }. Вызов yield запускает переданный блок.
# Блок можно принять явно параметром: def run(&block); block.call; end.
def twice
  yield
  yield
end

twice { puts "Hello from block!" }

# Лямбда - объект, который хранит код и вызывается через call.
# ->(x) { ... } - короткая запись; альтернативная запись: lambda { |x| x * x }.
# В отличие от обычного блока, лямбда строго проверяет число аргументов.
lambda_func = ->(x) { x * x }
puts lambda_func.call(5)  # 25

# 7. Классы
# class описывает собственный тип объектов. initialize автоматически вызывается
# при User.new и обычно используется для начальной настройки объекта.
class User
  # attr_reader создаёт только чтение, attr_writer - только запись,
  # attr_accessor - и чтение, и запись. Здесь доступны user.name и user.age,
  # а также user.name = "Другой пользователь".
  attr_accessor :name, :age

  def initialize(name, age)
    # @name и @age - переменные экземпляра: у каждого User своё значение.
    # Они доступны внутри методов объекта, но не напрямую снаружи.
    @name = name
    @age = age
  end

  def info
    "User: #{@name}, #{@age} years old"
  end

  # to_s задаёт строковое представление объекта. Поэтому puts user
  # автоматически вызывает user.to_s.
  def to_s
    info
  end
end

user = User.new("Alex", 30)
puts user