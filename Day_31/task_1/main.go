// ============================================================
// ЗАДАНИЕ 1: CLI-УТИЛИТА С ФЛАГАМИ
// ============================================================
// Цель: научиться создавать программу, которая принимает
// параметры из командной строки через флаги.
//
// Что делаем:
// 1. Определяем флаги: -file, -from, -to, -stats
// 2. Выводим их значения
// 3. Проверяем, существует ли файл
// ============================================================

package main

import (
	"flag" // Пакет для работы с флагами командной строки
	"fmt"  // Для вывода в консоль
	"os"   // Для работы с файловой системой (проверка файлов)
)

// ============================================================
// ОСНОВНАЯ ФУНКЦИЯ
// ============================================================
func main() {
	// -----------------------------------------------------------------
	// ШАГ 1: ОПРЕДЕЛЯЕМ ФЛАГИ
	// -----------------------------------------------------------------
	// flag.String() - создаёт флаг со строковым значением
	// Параметры: (имя_флага, значение_по_умолчанию, описание)
	// Возвращает: указатель на строку (*string)
	// -----------------------------------------------------------------
	filePath := flag.String("file", "logs.txt", "путь к файлу логов")
	fromDate := flag.String("from", "", "начальная дата (YYYY-MM-DD)")
	toDate := flag.String("to", "", "конечная дата (YYYY-MM-DD)")

	// flag.Bool() - создаёт флаг с булевым значением (true/false)
	showStats := flag.Bool("stats", false, "показать статистику")

	// -----------------------------------------------------------------
	// ШАГ 2: ПАРСИМ ФЛАГИ
	// -----------------------------------------------------------------
	// flag.Parse() - обрабатывает все флаги, переданные в командной строке
	// Без этого вызова флаги не будут работать
	// -----------------------------------------------------------------
	flag.Parse()

	// -----------------------------------------------------------------
	// ШАГ 3: ВЫВОДИМ ЗНАЧЕНИЯ ФЛАГОВ
	// -----------------------------------------------------------------
	// Чтобы получить значение флага, нужно разыменовать указатель (*)
	// Например: *filePath даёт строку, а не указатель на неё
	// -----------------------------------------------------------------
	fmt.Println("Параметры запуска")
	fmt.Println("Файл:", *filePath) // Разыменовываем указатель
	fmt.Println("От:", *fromDate)
	fmt.Println("До:", *toDate)
	fmt.Println("Статистика:", *showStats)

	// -----------------------------------------------------------------
	// ШАГ 4: ПРОВЕРЯЕМ, СУЩЕСТВУЕТ ЛИ ФАЙЛ
	// -----------------------------------------------------------------
	// os.Stat() - получает информацию о файле
	// Если файл не существует - возвращает ошибку
	// os.IsNotExist() - проверяет, является ли ошибка "файл не найден"
	// -----------------------------------------------------------------
	if _, err := os.Stat(*filePath); os.IsNotExist(err) {
		// Если файла нет - выводим ошибку и завершаем программу
		fmt.Printf("Ошибка: файл '%s' не существует!\n", *filePath)
		os.Exit(1) // 1 - код ошибки (программа завершается с ошибкой)
	}

	// Если дошли до этой строки - файл существует
	fmt.Println("Файл существует!")
}
